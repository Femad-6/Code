/**
 * ============================================================================
 * 物联网设备身份验证实验 - Schnorr 身份识别协议实现
 * ============================================================================
 *
 * 实验名称：基于 Schnorr 协议的物联网设备身份认证
 * 实验目的：演示零知识证明协议在设备身份验证中的应用
 *
 * Schnorr 协议原理：
 * -----------------------------------------------------------
 * Schnorr 协议是一种经典的零知识证明协议，允许证明者向验证者证明
 * 他拥有某个私钥，而无需泄露私钥本身的内容。
 *
 * 数学背景：
 * - 选择一个大素数 P 和其原根 G
 * - 私钥 x 是随机数，满足 0 < x < Q
 * - 公钥 y = G^x mod P
 *
 * 认证流程（三次握手）：
 * 1. 承诺阶段：证明者选择随机数 v，计算 C = G^v mod P 并发送给验证者
 * 2. 挑战阶段：验证者发送随机挑战 e
 * 3. 响应阶段：证明者计算 s = (v + e*x) mod Q 并发送
 * 4. 验证阶段：验证者检查 G^s mod P = C*y^e mod P 是否成立
 *
 * 安全性分析：
 * - 如果等式成立，说明证明者确实知道私钥 x
 * - 即使攻击者截获了 C、e、s，也无法推导出私钥 x
 * - 每次认证使用不同的随机数 v，防止重放攻击
 *
 * ============================================================================
 */

#include <stdio.h>
#include <stdlib.h>
#include <time.h>
#include <math.h>

/**
 * ============================================================================
 * 模幂运算函数：计算 (base^exp) mod mod
 * ============================================================================
 *
 * 功能：高效计算大整数的模幂运算
 * 算法：快速幂（二分指数）算法
 * 时间复杂度：O(log exp)
 *
 * 参数说明：
 *   base - 底数
 *   exp  - 指数
 *   mod  - 模数
 *
 * 返回值：(base^exp) mod mod 的结果
 *
 * 算法原理：
 *   将指数 exp 转换为二进制，例如 exp = 13 = 1101(二进制)
 *   base^13 = base^8 * base^4 * base^1
 *   每次循环将指数右移一位，底数平方，从而高效计算
 */
long long mod_exp(int base, int exp, int mod)
{
    long long result = 1;
    base = base % mod;

    // 循环处理指数的每一位
    while (exp > 0)
    {
        // 如果当前位为1，则累乘到结果中
        if (exp % 2 == 1)
        {
            result = (result * base) % mod;
        }
        // 指数右移一位（除以2）
        exp = exp / 2;
        // 底数平方
        base = (base * base) % mod;
    }
    return result;
}

/**
 * ============================================================================
 * 模逆运算函数：计算 a 关于模 m 的乘法逆元
 * ============================================================================
 *
 * 功能：求解方程 a*x ≡ 1 (mod m) 中的 x
 * 算法：扩展欧几里得算法
 *
 * 参数说明：
 *   a - 需要求逆的数
 *   m - 模数
 *
 * 返回值：a 的模 m 乘法逆元，即满足 (a*x) mod m = 1 的 x
 *
 * 注意：本程序中此函数未被调用，仅作扩展功能保留
 */
long long mod_inverse(int a, int m)
{
    int m0 = m, y = 0, x = 1;

    // 边界情况：当模数为1时，不存在逆元
    if (m == 1)
        return 0;

    // 扩展欧几里得算法
    while (a > 1)
    {
        // 计算商
        int q = a / m;
        int t = m;

        // 辗转相除
        m = a % m;
        a = t;

        // 更新系数
        t = y;
        y = x - q * y;
        x = t;
    }

    // 处理负数情况，确保结果为正
    if (x < 0)
        x += m0;
    return x;
}

/**
 * ============================================================================
 * 主函数：执行 Schnorr 身份识别协议
 * ============================================================================
 */
int main()
{
    // ===== 系统公共参数（由权威机构预先选定）=====
    int G = 2;   // 生成元，原根
    int P = 23;  // 大素数（实验中选用小素数便于演示）
    int Q = 11;  // Q 是 P-1 的素因子，用于限制随机数范围

    // ===== 设备密钥对 =====
    int x = 10;  // 设备私钥（只有设备知道，用于证明身份）
    int y = mod_exp(G, x, P);  // 设备公钥（公开，用于验证）

    // ===== 认证配置 =====
    int rounds = 10;        // 执行10轮认证验证
    int success_count = 0;  // 成功验证计数器

    /**
     * 预定义的随机数序列：
     * v_values：承诺阶段的随机数（证明者选择的随机nonce）
     * e_values：挑战阶段的随机数（验证者发送的挑战）
     *
     * 注意：在实际应用中，这些随机数应该动态生成
     * 这里使用固定序列是为了确保输出可重现
     */
    int v_values[] = {5, 4, 8, 8, 5, 1, 1, 5, 7, 1};
    int e_values[] = {5, 10, 5, 1, 9, 6, 3, 6, 4, 2};

    // ===== 输出系统公共参数 =====
    printf("物联网设备身份验证实验（多次验证）\n");
    printf("公开参数:\n");
    printf("G = %d, P = %d, Q = %d\n", G, P, Q);
    printf("设备私钥 x = %d\n", x);
    printf("设备公钥 y = %d^%d mod %d = %d\n\n", G, x, P, y);

    /**
     * =========================================================================
     * 执行多轮 Schnorr 认证协议
     * =========================================================================
     */
    for (int i = 0; i < rounds; i++)
    {
        // ----- 第一步：承诺阶段 -----
        // 设备选择随机数 v，计算承诺值 C = G^v mod P
        int v = v_values[i];
        int C = mod_exp(G, v, P);

        // ----- 第二步：挑战阶段 -----
        // 服务器/验证者发送随机挑战 e
        int e = e_values[i];

        // ----- 第三步：响应阶段 -----
        // 设备使用私钥 x 计算响应 s = (v + e*x) mod Q
        // 注意：这里巧妙地将私钥 x 融入计算，但不会泄露 x
        int s = (v + e * x) % Q;

        // ----- 第四步：验证阶段 -----
        // 验证者检查等式：G^s mod P = C*y^e mod P
        //
        // 数学推导：
        // 如果等式成立，说明：
        //   G^s ≡ C*y^e (mod P)
        //   G^(v+ex) ≡ G^v * (G^x)^e (mod P)
        //   G^v * G^(ex) ≡ G^v * G^(ex) (mod P)  [恒成立]
        //
        // 因此，只有知道私钥 x 的设备才能计算出正确的 s 值

        long long left = mod_exp(G, s, P);           // G^s mod P
        long long right = (C * mod_exp(y, e, P)) % P; // C*y^e mod P

        // ----- 输出认证过程详情 -----
        printf("[认证阶段]\n");
        printf("%d. 设备发送承诺 C = %d^%d mod %d = %lld\n", i + 1, G, v, P, C);
        printf("%d. 服务器发送挑战 e = %d\n", i + 1, e);
        printf("%d. 设备响应 s = (%d + %d*%d) mod %d = %lld\n\n", i + 1, v, e, x, Q, s);

        printf("[验证阶段]\n");
        printf("验证等式: G^s mod P = C*y^c mod P\n");
        printf("计算结果: %d ≡ %d mod %d\n", left, right, P);

        // ----- 判断验证结果 -----
        if (left == right)
        {
            printf("验证结果: 通过\n\n");
            success_count++;
        }
        else
        {
            printf("验证结果: 失败\n\n");
        }
    }

    // ===== 输出最终统计结果 =====
    printf("验证成功次数: %d/%d\n", success_count, rounds);

    return 0;
}

